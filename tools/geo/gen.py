"""Generate Dopaccess map assets.

Inputs (download first, not committed):
  ne_10m_admin_1_states_provinces.geojson  Natural Earth (public domain)
  geotargets-*.csv                         Google Ads geo targets (criteria IDs = GA4 cityId)
  tilemap_packed.png                       Kenney "RPG Urban Pack" (CC0)

Outputs:
  android/.../res/drawable-nodpi/jp_map.png      pixel base map (no people)
  android/.../res/drawable-nodpi/people.png      6 people x 3 frames x 4 dirs (16px tiles)
  android/.../widget/MapData.kt                  prefecture anchor points
  backend/src/jpcities.ts                        cityId -> prefecture code
Usage: python3 gen.py <admin1.geojson> <geotargets.csv> <tilemap_packed.png>
"""
import csv, json, math, sys, unicodedata
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
ADMIN1, GT, TILES = sys.argv[1:4]
W = 333                  # low-res canvas width; widget upscales with nearest-neighbour
HS = [140, 175, 210, 250]  # one map per widget shape, so the land always fills it
OKW = 30                 # Okinawa inset width (bottom-left)
OS_W, OS_H = 58, 30      # overseas box (bottom-right)
SEA, SEA2 = (28, 58, 98), (40, 78, 125)
LAND, EDGE = (96, 150, 84), (62, 104, 60)

def norm(n):
    n = ''.join(c for c in unicodedata.normalize('NFKD', n) if not unicodedata.combining(c))
    return n.lower().replace(' prefecture', '').replace('-', '')

feats = [f for f in json.load(open(ADMIN1))['features'] if f['properties'].get('adm0_a3') == 'JPN']
iso = {f['properties']['iso_3166_2']: f for f in feats}

SHEAR = 0.55
def proj(lon, lat, code):
    if code == 'JP-01':  # Hokkaido nudged (deformed map)
        lon += 0.2; lat += 0.6
    x = (lon - 137.5) * math.cos(math.radians(37)); y = -(lat - 37.5)
    return x, y + SHEAR * x

def rings(f):
    g = f['geometry']
    return [p[0] for p in (g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']])]

polys, oki = {}, []
for code, f in iso.items():
    rs = rings(f)
    if code == 'JP-47':
        oki = [r for r in rs if len(r) > 30 and 127.5 < r[0][0] < 128.5 and 26 < r[0][1] < 27]
        continue
    polys[code] = [[proj(c[0], c[1], code) for c in r] for r in rs
                   if len(r) > 40 and 128.5 < r[0][0] < 146.2 and 30.8 < r[0][1] < 45.6]

pts = [q for ps in polys.values() for p in ps for q in p]
minx, maxx = min(p[0] for p in pts), max(p[0] for p in pts)
miny, maxy = min(p[1] for p in pts), max(p[1] for p in pts)
def draw_map(H):
    mx0, mx1, my0, my1 = OKW + 2, W - 6, 6, H - 3
    scx, scy = (mx1 - mx0) / (maxx - minx), (my1 - my0) / (maxy - miny)
    tp = lambda p: (mx0 + (p[0] - minx) * scx, my0 + (p[1] - miny) * scy)

    im = Image.new('RGBA', (W, H), SEA + (255,)); d = ImageDraw.Draw(im)
    import random
    rnd = random.Random(3)
    for _ in range(180):
        x, y = rnd.randrange(W), rnd.randrange(H); d.line([x, y, x + 2, y], fill=SEA2)
    anchors = {}
    for code, ps in polys.items():
        for p in ps:
            d.polygon([tp(a) for a in p], fill=LAND, outline=EDGE)
        big = max(ps, key=len)
        anchors[int(code[3:])] = tp((sum(p[0] for p in big) / len(big), sum(p[1] for p in big) / len(big)))
    # Okinawa inset, bordered by a mirrored-「 line
    iy = H - 26
    d.line([(0, iy), (OKW, iy), (OKW, H)], fill=(220, 230, 240))
    oc = [c for r in oki for c in r]
    ax0, ax1 = min(c[0] for c in oc), max(c[0] for c in oc)
    ay0, ay1 = min(c[1] for c in oc), max(c[1] for c in oc)
    k = min((OKW - 10) / (ax1 - ax0), (H - iy - 8) / (ay1 - ay0))
    otp = lambda c: (5 + (c[0] - ax0) * k, iy + 4 + (ay1 - c[1]) * k)
    for r in oki:
        d.polygon([otp(c) for c in r], fill=LAND, outline=EDGE)
    anchors[47] = otp(((ax0 + ax1) / 2, (ay0 + ay1) / 2))
    return im, anchors

res = ROOT / 'android/app/src/main/res/drawable-nodpi'; res.mkdir(parents=True, exist_ok=True)
maps = [draw_map(h) for h in HS]
for i, (im, _) in enumerate(maps):
    im.save(res / f'jp_map_{i}.png')
Image.open(TILES).convert('RGBA').crop((23 * 16, 0, 27 * 16, 18 * 16)).save(res / 'people.png')

kt = ROOT / 'android/app/src/main/java/jp/dopaccess/widget/widget/MapData.kt'
fa = lambda a, j: 'floatArrayOf(' + ', '.join(f'{a[i][j]:.1f}f' for i in range(1, 48)) + ')'
xs = ',\n        '.join(fa(a, 0) for _, a in maps)
ys = ',\n        '.join(fa(a, 1) for _, a in maps)
hs = ', '.join(map(str, HS))
kt.write_text(f'''// Generated by tools/geo/gen.py. Do not edit by hand.
package jp.dopaccess.widget.widget

object MapData {{
    /** Map variants jp_map_0..n: all W wide, heights in HS. */
    const val W = {W}
    val HS = intArrayOf({hs})
    const val OS_W = {OS_W}
    const val OS_H = {OS_H}
    /** Anchor point per variant, then per prefecture code 1..47 (index 0 = code 1), in map pixels. */
    val prefX = arrayOf(
        {xs},
    )
    val prefY = arrayOf(
        {ys},
    )
}}
''')

rows = {r['Criteria ID']: r for r in csv.DictReader(open(GT, encoding='utf-8'))}
name2code = {norm(f['properties']['name']): int(c[3:]) for c, f in iso.items()}
by = {}
for cid, r in rows.items():
    if r['Country Code'] != 'JP' or r['Target Type'] in ('Postal Code', 'Country', 'TV Region'):
        continue
    x = r
    while x and x['Target Type'] != 'Prefecture':
        x = rows.get(x['Parent ID'])
    if x and norm(x['Name']) in name2code:
        by.setdefault(name2code[norm(x['Name'])], []).append(int(cid))
lines = ',\n'.join(f'  {p}: [{",".join(map(str, sorted(v)))}]' for p, v in sorted(by.items()))
(ROOT / 'backend/src/jpcities.ts').write_text(f'''// Generated by tools/geo/gen.py from the Google Ads geo targets list.
// GA4 realtime `cityId` -> Japanese prefecture code (JIS X 0401, 1..47).
const BY_PREF: Record<number, number[]> = {{
{lines},
}};

const MAP = new Map<string, number>();
for (const [pref, ids] of Object.entries(BY_PREF)) for (const id of ids) MAP.set(String(id), Number(pref));

export function prefOfCity(cityId: string | undefined | null): number | null {{
  if (!cityId) return null;
  return MAP.get(cityId) ?? null;
}}
''')
print('ok', len(maps[0][1]), sum(len(v) for v in by.values()))
